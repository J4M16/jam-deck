"use strict";
const fs = require("fs");
const path = require("path");
const crypto = require("crypto");
const zlib = require("zlib");
const assert = require("assert");
const root = path.resolve(__dirname, "..");
const source = fs.readFileSync(path.join(root, "main.js"), "utf8");
const payload = JSON.parse(source.match(/const ISLAND_GLASS_PAYLOAD = (.+);/)[1]);
const hash = bytes => crypto.createHash("sha256").update(bytes).digest("hex");
const helper = zlib.gunzipSync(Buffer.from(payload.windows.gzip, "base64"));
assert.equal(helper.toString("ascii", 0, 2), "MZ");
assert.equal(hash(helper), payload.windows.sha256, "three-file plugin contains an intact Windows helper");
const cpp = fs.readFileSync(path.join(root, "native/island-glass/windows.cpp"), "utf8").replace(/\r\n/g, "\n");
assert.equal(hash(cpp), payload.windows.sourceSha256, "native source changes require rebuilding the embedded helper");
const mac = fs.readFileSync(path.join(root, "native/island-glass/macos.js"), "utf8").replace(/\r\n/g, "\n");
assert.equal(payload.macos.source, mac, "macOS built-in AppKit host ships inside the standard plugin");
assert.equal(hash(mac), payload.macos.sha256);
assert(cpp.includes("WINEVENT_OUTOFCONTEXT") && cpp.includes("WM_CLOSE"), "native host follows window lifecycle without polling");
assert(mac.includes("NSVisualEffectBlendingModeBehindWindow") && mac.includes("effect.maskImage = mask"));
console.log("Island glass: embedded payload integrity and both platform sources passed");
