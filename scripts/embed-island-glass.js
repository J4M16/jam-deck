"use strict";
const fs = require("fs");
const crypto = require("crypto");
const zlib = require("zlib");
const path = require("path");
const root = path.resolve(__dirname, "..");
const digest = bytes => crypto.createHash("sha256").update(bytes).digest("hex");
const windows = fs.readFileSync(path.join(root, ".cache/island-glass.exe"));
const readSource = file => fs.readFileSync(path.join(root, file), "utf8").replace(/\r\n/g, "\n");
const macos = readSource("native/island-glass/macos.js");
const payload = {
  windows: { sha256: digest(windows), sourceSha256: digest(readSource("native/island-glass/windows.cpp")), gzip: zlib.gzipSync(windows, { level: 9 }).toString("base64") },
  macos: { sha256: digest(macos), source: macos },
};
const target = path.join(root, "main.js");
const source = fs.readFileSync(target, "utf8");
const marker = /\/\/ BEGIN ISLAND GLASS PAYLOAD[\s\S]*?\/\/ END ISLAND GLASS PAYLOAD/;
if (!marker.test(source)) throw Error("Island glass payload marker missing");
fs.writeFileSync(target, source.replace(marker, () => `// BEGIN ISLAND GLASS PAYLOAD (generated by scripts/embed-island-glass.js)\nconst ISLAND_GLASS_PAYLOAD = ${JSON.stringify(payload)};\n// END ISLAND GLASS PAYLOAD`));
console.log(`Embedded Windows helper ${windows.length} bytes and macOS AppKit source.`);
