"use strict";
const fs = require("fs"), path = require("path"), crypto = require("crypto"), zlib = require("zlib");
const root = path.resolve(__dirname, "..");
const read = file => fs.readFileSync(path.join(root, file), "utf8").replace(/\r\n/g, "\n");
const hash = value => crypto.createHash("sha256").update(value).digest("hex");
const executable = path.join(root, ".cache/island-capture-macos-arm64/island-capture-macos-arm64");
const bytes = fs.readFileSync(executable);
const payload = { sha256: hash(bytes), sourceSha256: hash(read("native/island-capture/main.swift")), gzip: zlib.gzipSync(bytes, { level: 9 }).toString("base64") };
const renderer = read("native/island-capture/renderer.js"), controller = read("native/island-capture/controller.js");
const target = path.join(root, "main.js"), source = fs.readFileSync(target, "utf8");
const marker = /\/\/ BEGIN ISLAND CAPTURE BUNDLE[\s\S]*?\/\/ END ISLAND CAPTURE BUNDLE/;
if (!marker.test(source)) throw Error("Capture bundle marker missing");
const block = `// BEGIN ISLAND CAPTURE BUNDLE (generated by scripts/embed-island-capture.js)\nconst MACOS_ISLAND_CAPTURE_PAYLOAD = ${JSON.stringify(payload)};\n${renderer}\n${controller}\n// END ISLAND CAPTURE BUNDLE`;
fs.writeFileSync(target, source.replace(marker, () => block));
console.log(`Embedded island capture; Apple Silicon helper ${bytes.length} bytes.`);
