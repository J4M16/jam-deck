"use strict";
const fs = require("fs"), path = require("path"), crypto = require("crypto"), zlib = require("zlib");
const root = path.resolve(__dirname, "..");
const read = file => fs.readFileSync(path.join(root, file), "utf8").replace(/\r\n/g, "\n");
const hash = value => crypto.createHash("sha256").update(value).digest("hex");
const bundle = (binary, source) => {
  const bytes = fs.readFileSync(path.join(root, binary));
  return {sha256:hash(bytes), sourceSha256:hash(read(source)), gzip:zlib.gzipSync(bytes,{level:9}).toString("base64")};
};
const win = bundle(".cache/external-drag-windows-x64/external-drag-windows-x64.node", "native/external-drag/main.cpp");
const mac = bundle(".cache/external-drag-macos-arm64/external-drag-macos-arm64.node", "native/external-drag/main.mm");
const controller = read("native/external-drag/controller.js");
const block = `// BEGIN EXTERNAL DRAG BUNDLE (generated by scripts/embed-external-drag.js)\nconst WINDOWS_EXTERNAL_DRAG_PAYLOAD = ${JSON.stringify(win)};\nconst MACOS_EXTERNAL_DRAG_PAYLOAD = ${JSON.stringify(mac)};\n${controller}\n// END EXTERNAL DRAG BUNDLE`;
const target = path.join(root,"main.js"), source = fs.readFileSync(target,"utf8");
const marker = /\/\/ BEGIN EXTERNAL DRAG BUNDLE[^\n]*\n[\s\S]*?\/\/ END EXTERNAL DRAG BUNDLE/;
if (!marker.test(source)) throw Error("External drag bundle marker missing");
fs.writeFileSync(target,source.replace(marker,()=>block));
console.log("Embedded Windows x64 and macOS arm64 external drag helpers.");
